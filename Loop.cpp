// Loop in C++ Language-


#include <iostream>
using namespace std;

// 1. for loop

//code-

int main() {
    for(int i=0;i<=10;i++){
        cout<<i<<endl;
    }
    return 0;
}

// 2. while Loop

//code-

int main(){
    int i=0;
    while(i<=10){
        cout<<i<<endl;
        i++;
    }
}

// 3. do-while Loop

//code-

int main(){
    int i=0;
    do{
        cout<<i<<endl;
        i++;
    }while(i<=10);
}

